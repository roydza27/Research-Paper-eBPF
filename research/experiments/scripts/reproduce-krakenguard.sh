#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
BASELINE_DIR="${KRAKENGUARD_ARTIFACT_DIR:-$ROOT/research/baselines/krakenguard/artifact}"
RESULT_DIR="${KRAKENGUARD_RESULT_DIR:-$ROOT/research/experiments/results/krakenguard}"
COMMIT="e7bd84005b304c5a10efcdb04914d1882b3cccf7"
REPO="https://github.com/krakenguard-ebpf/krakenguard.git"
TIMEOUT_SECONDS="${TIMEOUT_SECONDS:-300}"

mkdir -p "$RESULT_DIR" "$BASELINE_DIR"

log() { printf '[krakenguard] %s\n' "$*" | tee -a "$RESULT_DIR/reproduction.log"; }
fail() { log "ERROR: $*"; exit 1; }

command -v git >/dev/null || fail "git is required"
command -v python3 >/dev/null || fail "python3 is required"
command -v docker >/dev/null || fail "docker is required for the preferred artifact path"

docker compose version >/dev/null 2>&1 || fail "docker compose is required"

log "repository root: $ROOT"
log "artifact commit: $COMMIT"
log "result directory: $RESULT_DIR"

# Freeze the actual research host using the repository's existing collector.
ENV_COLLECTOR="$ROOT/research/experiments/environment/collect-environment.sh"
if [[ -x "$ENV_COLLECTOR" ]]; then
  log "collecting host environment"
  "$ENV_COLLECTOR" > "$RESULT_DIR/environment.json"
else
  log "WARNING: environment collector unavailable; record host metadata manually"
fi

if [[ ! -d "$BASELINE_DIR/.git" ]]; then
  log "cloning KRAKENGUARD with submodules"
  git clone --recurse-submodules "$REPO" "$BASELINE_DIR" >> "$RESULT_DIR/reproduction.log" 2>&1
fi

cd "$BASELINE_DIR"
git fetch --tags --force origin >> "$RESULT_DIR/reproduction.log" 2>&1 || true
git checkout --detach "$COMMIT" >> "$RESULT_DIR/reproduction.log" 2>&1
git submodule sync --recursive >> "$RESULT_DIR/reproduction.log" 2>&1
git submodule update --init --recursive >> "$RESULT_DIR/reproduction.log" 2>&1

ACTUAL_COMMIT="$(git rev-parse HEAD)"
[[ "$ACTUAL_COMMIT" == "$COMMIT" ]] || fail "artifact commit mismatch: $ACTUAL_COMMIT"

git status --short > "$RESULT_DIR/artifact-status.txt"
git submodule status --recursive > "$RESULT_DIR/submodules.txt"

log "building the documented Docker artifact"
docker compose build --pull > "$RESULT_DIR/docker-build.log" 2>&1

log "starting verification-only daemon"
docker compose up -d > "$RESULT_DIR/docker-up.log" 2>&1
trap 'docker compose down >/dev/null 2>&1 || true' EXIT

log "waiting for daemon socket"
for _ in $(seq 1 60); do
  [[ -S "$BASELINE_DIR/socket/krakenguard.sock" ]] && break
  sleep 1
done
[[ -S "$BASELINE_DIR/socket/krakenguard.sock" ]] || fail "KrakenGuard daemon socket did not appear"

log "health check"
python3 daemon/test_client.py health > "$RESULT_DIR/health.log" 2>&1 || true

run_target() {
  local target="$1"
  local slug
  slug="$(printf '%s' "$target" | tr '/:' '__')"
  log "running official target: $target"
  if timeout "$TIMEOUT_SECONDS" python3 examples/daemon_submit_one_example.py --target "$target" > "$RESULT_DIR/$slug.log" 2>&1; then
    printf 'completed\n' > "$RESULT_DIR/$slug.status"
  else
    rc=$?
    if [[ "$rc" -eq 124 ]]; then
      printf 'timeout\n' > "$RESULT_DIR/$slug.status"
    else
      printf 'failed:%s\n' "$rc" > "$RESULT_DIR/$slug.status"
    fi
  fi
}

# The smoke target is intentionally small. The remaining targets are representative
# published workloads and are run only after the smoke target has been attempted.
run_target "fw:test-object"

if [[ "${RUN_OFFICIAL:-1}" == "1" ]]; then
  run_target "electrode:test-object-reply"
  run_target "electrode:test-object-quorum"
  run_target "katran:test-object"
  run_target "cross_prog:test-object-fastreply"
  run_target "cross_prog:test-object-quorum"
fi

log "reproduction run complete; raw logs are under $RESULT_DIR"
log "no research conclusion is generated by this script"
